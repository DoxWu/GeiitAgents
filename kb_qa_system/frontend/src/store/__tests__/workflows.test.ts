  expect(completeModel).toHaveBeenCalledTimes(2);
  expect(vi.mocked(completeModel).mock.calls.map(call => [call[0].model, call[1]])).toEqual([['fixture-model', 'local-key'], ['relay-model', 'relay-key']]);
