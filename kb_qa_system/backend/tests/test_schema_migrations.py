def test_sqlite_metadata_and_database_defaults():
    engine = create_engine("sqlite://")
    try:
        Base.metadata.create_all(engine)
        with engine.begin() as conn:
            # Raw SQL deliberately omits defaults so the database supplies them.
            user_id = conn.execute(
                text("""
                INSERT INTO users (username, email, hashed_password)
                VALUES ('schema-test', 'schema@example.invalid', 'synthetic') RETURNING id
                """)
            ).scalar_one()
            user = conn.execute(
                text("SELECT is_active, is_superuser, user_type FROM users WHERE id=:id"),
                {"id": user_id},
            ).one()
            assert tuple(user) == (1, 0, "regular")
            conn.execute(
                text("""
                INSERT INTO organizations (id, name, slug) VALUES (1, 'Schema', 'schema')
                """)
            )
            conn.execute(
                text("""
                INSERT INTO organization_memberships (organization_id, user_id)
                VALUES (1, :user_id)
                """),
                {"user_id": user_id},
            )
            assert tuple(
                conn.execute(text("SELECT description, is_active FROM organizations")).one()
            ) == ("", 1)
            assert tuple(
                conn.execute(text("SELECT role, status FROM organization_memberships")).one()
            ) == ("member", "pending")
            conn.execute(
                text("""
                INSERT INTO shared_agents (id, owner_id, name, definition)
                VALUES ('schema-agent', :user_id, 'Schema agent', '{}')
                """),
                {"user_id": user_id},
            )
            assert conn.execute(text("SELECT summary FROM shared_agents")).scalar_one() == ""
        # PostgreSQL-only index expressions must not reach SQLite create_all.
        names = {index["name"] for index in inspect(engine).get_indexes("document_chunks")}
        assert "ix_document_chunks_content_tsv" not in names
        assert "ix_document_chunks_content_vector" not in names
    finally:
        engine.dispose()


def test_live_schema_matches_models_and_detects_drift(live):  # noqa: F811
    cfg, _ = live
    cfg = seeded(cfg)
    config = migration_config()
    config.attributes["database_url"] = cfg.DATABASE_URL
    config.attributes["ops_settings"] = cfg
    # Includes default/type/nullability/index comparisons from the real env.py.
    command.check(config)

    with connect(cfg.DATABASE_URL, cfg) as conn:
        column_type = conn.execute("""
            SELECT format_type(atttypid, atttypmod) FROM pg_attribute
            WHERE attrelid='document_chunks'::regclass AND attname='content_vector'
        """).fetchone()[0]
        assert column_type == f"vector({settings.EMBEDDING_DIMENSION})"
        indexes = conn.execute("""
            SELECT c.relname, i.indisvalid FROM pg_index i
            JOIN pg_class c ON c.oid=i.indexrelid
            WHERE c.relname IN (
                'ix_document_chunks_content_vector', 'ix_document_chunks_content_tsv',
                'ix_documents_visibility_deleted', 'uq_reminder_occurrence'
            )
        """).fetchall()
        assert len(indexes) == 4
        assert all(valid for _, valid in indexes)
        conn.execute("ALTER TABLE organizations ALTER COLUMN description SET DEFAULT 'drift'")

    # The check must still catch real drift; none of these properties is ignored.
    with pytest.raises(AutogenerateDiffsDetected, match="modify_default"):
        command.check(config)


def test_live_existing_rows_and_indexes_survive_resource_upgrade(live):  # noqa: F811
    cfg, _ = live
    config = migration_config()
    config.attributes["database_url"] = cfg.DATABASE_URL
    config.attributes["ops_settings"] = cfg
    command.upgrade(config, "20261010_0010")
    with connect(cfg.DATABASE_URL, cfg) as conn:
        user_id = conn.execute("""
            INSERT INTO users (username, email, hashed_password, created_at, updated_at)
            VALUES ('legacy', 'legacy@example.invalid', 'synthetic', NULL, NULL)
            RETURNING id
        """).fetchone()[0]
        doc_id = conn.execute(
            """
            INSERT INTO documents (
                title, file_name, file_path, file_type, file_size, user_id, content,
                created_at, updated_at
            ) VALUES ('Legacy', 'legacy.txt', 'synthetic/legacy.txt', 'txt', 10, %s,
                      'Synthetic legacy text', NULL, NULL) RETURNING id
        """,
            (user_id,),
        ).fetchone()[0]
        vector = [1.0] + [0.0] * (settings.EMBEDDING_DIMENSION - 1)
        conn.execute(
            """
            INSERT INTO document_chunks (
                document_id, chunk_index, content, content_vector, created_at
            ) VALUES (%s, 0, 'Synthetic legacy text', %s::vector, NULL)
        """,
            (doc_id, str(vector)),
        )
        before = conn.execute(
            """
            SELECT content, content_vector::text, token_count, created_at
            FROM document_chunks WHERE document_id=%s
        """,
            (doc_id,),
        ).fetchone()
        old_indexes = conn.execute("""
            SELECT indexname, indexdef FROM pg_indexes WHERE schemaname='public'
            AND tablename IN ('documents', 'document_chunks') ORDER BY indexname
        """).fetchall()

    command.upgrade(config, "head")
    command.check(config)
    with connect(cfg.DATABASE_URL, cfg) as conn:
        assert (
            conn.execute(
                """
            SELECT content, content_vector::text, token_count, created_at
            FROM document_chunks WHERE document_id=%s
        """,
                (doc_id,),
            ).fetchone()
            == before
        )
        assert (
            conn.execute("""
            SELECT indexname, indexdef FROM pg_indexes WHERE schemaname='public'
            AND tablename IN ('documents', 'document_chunks')
            AND indexname NOT IN ('ix_documents_organization_id') ORDER BY indexname
        """).fetchall()
            == old_indexes
        )
        assert conn.execute(
            """
            SELECT created_at, updated_at, organization_id FROM documents WHERE id=%s
        """,
            (doc_id,),
        ).fetchone() == (None, None, None)
        assert (
            conn.execute("""
            SELECT to_regclass('public.ix_reminder_deliveries_reminder_id')
        """).fetchone()[0]
            is None
        )
